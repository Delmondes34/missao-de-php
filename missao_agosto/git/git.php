/*Aqui está uma lista completa de comandos Git:

Configuração

- git config --global user.name "Seu nome" (define nome do usuário)
- git config --global user.email "seuemail@example.com" (define email do usuário)
- git config --list (lista configurações atuais)
- git config --global --unset (remove configuração)

Criação e Clonagem

- git init (cria novo repositório)
- git clone url_do_repositório (clona repositório existente)
- git clone --bare url_do_repositório (clona repositório somente com metadados)

Gerenciamento de Arquivos

- git add arquivo.txt (adiciona arquivo ao stage)
- git add . (adiciona todos os arquivos ao stage)
- git rm arquivo.txt (remove arquivo do repositório)
- git mv arquivo.txt novo_nome.txt (renomeia arquivo)
- git add -i (adiciona arquivos interativamente)

Commit e Log

- git commit -m "mensagem" (cria novo commit)
- git log (exibe histórico de commits)
- git log --oneline (exibe histórico resumido)
- git show hash_do_commit (exibe detalhes de commit)
- git commit --amend (altera último commit)

Branches e Merge

- git branch nome_da_branch (cria nova branch)
- git checkout nome_da_branch (alterna para branch)
- git merge nome_da_branch (une branch com atual)
- git branch -d nome_da_branch (deleta branch)
- git branch -m nome_antigo nome_novo (renomeia branch)

Repositório Remoto

- git remote add origin url_do_repositório (adiciona repositório remoto)
- git fetch (atualiza repositório local com dados remotos)
- git push (envia alterações locais para repositório remoto)
- git pull (atualiza repositório local com alterações remotas)
- git remote -v (lista repositórios remotos)

Outros Comandos

- git status (exibe status do repositório)
- git diff (exibe diferenças entre arquivos)
- git reset (reverte alterações)
- git revert (reverte commit específico)
- git tag (cria marca de versão)
 
Mais comandos

- mv (mover ou mudar o nome)
- mkdir (Cria um diretório ou um subdiretório) 
- dir ou ls((-a (para exibir arquivos ocultos))) (para exibir arquivos)
- touche (criar arquivos)



